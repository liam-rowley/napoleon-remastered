"""The Empire-to-Napoleon discovery diff as a verb: check the six area files and render their README.

purpose: check discovery/diff/<area>.json against the diff schema and render discovery/diff/README.md (carry-over summary, then one table of every row that is not `same`)
usage: python3 core/wsc.py discovery check | discovery render
when: after any discovery pass (discovery/core/*.py) rewrites an area file; `check` also fails when the committed README is stale (tests/test_discovery.py runs it in the tests gate)
verb: discovery
"""
import json
import sys
from pathlib import Path

NAME = 'discovery'
HELP = 'the J6 Empire-to-Napoleon diff: check the area files, render discovery/diff/README.md'

AREAS = ('packs', 'layouts', 'fonts', 'lua_api', 'shaders', 'exe')
CELL = 90


def _load(root):
    sys.path.insert(0, str(Path(root) / 'discovery' / 'core'))
    from diffout import problems  # noqa: E402
    docs, bad = {}, []
    for a in AREAS:
        p = Path(root) / 'discovery' / 'diff' / f'{a}.json'
        if not p.exists():
            bad.append(f'{p}: missing')
            continue
        d = json.loads(p.read_text(encoding='utf-8'))
        bad += [f'{p}: {x}' for x in problems(d)]
        docs[a] = d
    return docs, bad


def _cell(v):
    s = str(v).replace('|', '/').replace('\n', ' ')
    return s if len(s) <= CELL else s[:CELL - 1] + '…'


def render(root):
    docs, bad = _load(root)
    if bad:
        raise ValueError('; '.join(bad))
    co = json.loads((Path(root) / 'discovery' / 'napoleon' / 'carry_over.json').read_text(encoding='utf-8'))
    out = ['# Empire to Napoleon diff (J6)', '',
           'Generated by `python3 core/wsc.py discovery render` from `discovery/diff/<area>.json` (written by `discovery/core/<area>.py`)',
           'and `discovery/napoleon/carry_over.json`. Do not edit. Inputs and re-run steps: `discovery/README.md`.', '',
           '## Carry-over of Empire tools', '', '| Tool family | Verdict | Note |', '|---|---|---|']
    out += [f"| {_cell(f['family'])} | {f['verdict']} | {_cell(f['note'])} |" for f in co['families']]
    out += ['', '## Rows', '', 'Every row whose verdict is not `same`; the `same` rows are counted per area. Full rows and detail: the area file.', '',
            '| Area | Same rows |', '|---|---|']
    out += [f"| {a} | {sum(r['verdict'] == 'same' for r in docs[a]['rows'])} of {len(docs[a]['rows'])} |" for a in AREAS]
    out += ['', '| Area | Item | Empire | Napoleon | Verdict | Adapter note | Evidence |', '|---|---|---|---|---|---|---|']
    for a in AREAS:
        for r in docs[a]['rows']:
            if r['verdict'] != 'same':
                out.append(f"| {a} | {_cell(r['item'])} | {_cell(r['empire'])} | {_cell(r['napoleon'])} | {r['verdict']} | "
                           f"{_cell(r['adapter'])} | {_cell(r['evidence'])} |")
    return '\n'.join(out) + '\n'


def add_arguments(p):
    p.add_argument('action', choices=('check', 'render'))


def run(args, ctx):
    root = Path(ctx.root)
    readme = root / 'discovery' / 'diff' / 'README.md'
    if args.action == 'render':
        text = render(root)
        readme.write_text(text, encoding='utf-8', newline='\n')
        print(f'{readme}: {len(text.encode())} bytes')
        return 0
    _, bad = _load(root)
    if not bad and (not readme.exists() or readme.read_text(encoding='utf-8') != render(root)):
        bad.append(f'{readme}: stale; run `wsc discovery render`')
    print('\n'.join(bad) or 'discovery: 6 area files valid, README current')
    return 1 if bad else 0
