#!/usr/bin/env python3
"""Expand the Napoleon library's $token RCSS sources into the stylesheets the viewer and the in-game host load.

purpose: build uikit/napoleon/dist (base.rcss, library.rcss, factions_synthetic.rcss) from src/*.rcss and tokens.json, check the committed copy, write a faction sheet, print sizes
usage: python3 uikit/napoleon/build.py [--check] [--stats] | faction-sheet <factions.json> <out.rcss>   (factions.json = {name: [r, g, b]}; the sheet is for install time, never committed with game values)
when: after any change to uikit/napoleon/src or tokens.json (the tests run --check); J35 and J53 call faction-sheet when they install; render.py stages screens through expand_file
not-a-verb: a build step for one folder, run by the tests and CI's viewer job, not a registry operation
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tokens as T  # noqa: E402

HERE = Path(__file__).resolve().parent
SRC = HERE / 'src'
DIST = HERE / 'dist'
BANNER = '/* GENERATED by uikit/napoleon/build.py from {what}: do not edit; change the source and run build.py. */\n'


def _default_block(tokens):
    rec = T.default_faction(tokens)
    return ('/* no faction set: accent_fill with white (LANGUAGE.md section 2); body.fac-<name> rules from a faction sheet override these */\n'
            'body {\n' + T.faction_decls(rec, tokens) + '}\n')


def library_parts():
    """The numbered library source files in load order (base.rcss is built separately: every screen links it first)."""
    return sorted(p for p in SRC.glob('[0-9]*.rcss'))


def build_all(tokens=None):
    """{dist file name: text}. Pure: no writes."""
    tokens = tokens or T.load_tokens()
    out = {}
    base = T.expand((SRC / 'base.rcss').read_text(encoding='utf-8'), tokens, 'src/base.rcss')
    out['base.rcss'] = BANNER.format(what='src/base.rcss, tokens.json') + base + _default_block(tokens)
    parts = [BANNER.format(what='src/*.rcss, tokens.json')]
    for p in library_parts():
        parts.append(f'/* ---- {p.name} ---- */\n' + T.expand(p.read_text(encoding='utf-8'), tokens, f'src/{p.name}'))
    out['library.rcss'] = ''.join(parts)
    synth = {k: v for k, v in tokens['faction_synthetic'].items() if not k.startswith('_')}
    out['factions_synthetic.rcss'] = (BANNER.format(what='tokens.json faction_synthetic') +
                                      '/* made-up and published colours only (France, Britain, light, dark, the 4.38 worst case): the board and the gates use these */\n'
                                      + T.faction_sheet(synth, tokens).split('*/\n', 1)[1])
    return out


BOARD_DATA = HERE.parents[1] / 'viewer' / 'napoleon' / 'board' / 'board_data.lua'


def _lua_str(v):
    return json.dumps(str(v))   # JSON string syntax is valid Lua for the plain ASCII we have


def board_data(tokens=None):
    """The component board's token swatches, contrast pairs and faction picker as a Lua table (generated: the board never types a ratio)."""
    tokens = tokens or T.load_tokens()
    lines = ['-- GENERATED by uikit/napoleon/build.py (board_data) from tokens.json: do not edit; run python3 uikit/napoleon/build.py',
             '-- purpose: the component board token swatches, contrast pairs and faction picker data, generated from tokens.json',
             '-- usage: loaded by viewer/napoleon/board/board.rml before board.lua; BoardData is read by Board.Init',
             '-- when: regenerated by uikit/napoleon/build.py whenever tokens.json changes',
             '-- not-a-verb: generated Lua data loaded by the board document in the viewer, not a command', '', 'BoardData = {', '	swatches = {']
    for name, hexv in T.all_colors(tokens).items():
        lines.append(f'		{{ name = {_lua_str(name)}, hex = {_lua_str(hexv)} }},')
    lines += ['	},', '	pairs = {']
    for fg, bg, mn, ratio, ok, what in T.pair_report(tokens):
        lines.append(f'		{{ fg = {_lua_str(fg)}, bg = {_lua_str(bg)}, min = {mn}, ratio = {ratio}, ok = {"true" if ok else "false"}, what = {_lua_str(what)} }},')
    lines += ['	},', '	factions = {']
    d = T.default_faction(tokens)
    lines.append(f'		{{ id = "default", label = "No faction (accent)", fac = {_lua_str(d["fac"])}, on = {_lua_str(d["on_fac"])}, ratio = {d["ratio"]}, adjusted = false }},')
    labels = {'france': 'France', 'britain': 'Britain', 'synth_light': 'Very light fill', 'synth_dark': 'Very dark fill', 'synth_worst': 'Worst case 4.38 (adjusted)'}
    for k, v in tokens['faction_synthetic'].items():
        if k.startswith('_'):
            continue
        r = T.faction_tokens(*v, tokens=tokens)
        lines.append(f'		{{ id = {_lua_str(k)}, label = {_lua_str(labels.get(k, k))}, fac = {_lua_str(r["fac"])}, on = {_lua_str(r["on_fac"])}, ratio = {r["ratio"]}, adjusted = {"true" if r["adjusted"] else "false"} }},')
    lines += ['	},', '}', '']
    return '\n'.join(lines)


def expand_file(path, tokens=None, extra=None):
    """Expand one authoring RCSS file (a screen's own sheet) with the same tokens; used by render.py's staging and J35's install."""
    return T.expand(Path(path).read_text(encoding='utf-8'), tokens, str(path), extra)


def check():
    """Problems between the committed dist and a fresh build (empty list = in step)."""
    problems = []
    for name, text in build_all().items():
        f = DIST / name
        if not f.exists():
            problems.append(f'dist/{name} missing')
        elif f.read_text(encoding='utf-8') != text:
            problems.append(f'dist/{name} differs from a fresh build')
    if BOARD_DATA.parent.exists() and (not BOARD_DATA.exists() or BOARD_DATA.read_text(encoding='utf-8') != board_data()):
        problems.append('viewer/napoleon/board/board_data.lua differs from a fresh build')
    for f in DIST.glob('*.rcss'):
        if f.name not in ('base.rcss', 'library.rcss', 'factions_synthetic.rcss'):
            problems.append(f'dist/{f.name} is not a build output')
    return problems


def stats():
    t = T.load_tokens()
    built = build_all(t)
    classes = set()
    for p in [SRC / 'base.rcss'] + library_parts():
        for sel in re.findall(r'([^{}]+)\{', re.sub(r'/\*.*?\*/', '', p.read_text(encoding='utf-8'), flags=re.S)):
            classes.update(re.findall(r'\.([A-Za-z_][\w-]*)', sel))
    return {
        'colour_tokens': len(t['color']), 'derived_colours': len(t['derived']), 'length_tokens': len(t['length']), 'type_styles': len(t['type']),
        'token_names': len(T.token_values(t)), 'library_classes': len(classes),
        'sheet_bytes': {k: len(v.encode('utf-8')) for k, v in built.items()},
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('cmd', nargs='?', default='build', choices=['build', 'faction-sheet'])
    ap.add_argument('args', nargs='*')
    ap.add_argument('--check', action='store_true', help='compare the committed dist with a fresh build; exit 1 when they differ')
    ap.add_argument('--stats', action='store_true')
    a = ap.parse_args()
    if a.cmd == 'faction-sheet':
        if len(a.args) != 2:
            ap.error('faction-sheet <factions.json> <out.rcss>')
        recs = {k: tuple(v) for k, v in json.loads(Path(a.args[0]).read_text(encoding='utf-8')).items()}
        Path(a.args[1]).write_text(T.faction_sheet(recs), encoding='utf-8', newline='\n')
        adj = [k for k, v in recs.items() if T.faction_tokens(*v)['adjusted']]
        print(f'build: faction sheet for {len(recs)} factions written to {a.args[1]}; fill adjusted for {len(adj)}' + (f': {", ".join(adj)}' if adj else ''))
        return 0
    if a.stats:
        print(json.dumps(stats(), indent=1))
        return 0
    if a.check:
        problems = check()
        for p in problems:
            print('build --check:', p)
        print('build --check:', 'dist is in step with src and tokens.json' if not problems else f'{len(problems)} problem(s): run python3 uikit/napoleon/build.py')
        return 1 if problems else 0
    DIST.mkdir(exist_ok=True)
    for name, text in build_all().items():
        (DIST / name).write_text(text, encoding='utf-8', newline='\n')
        print(f'build: dist/{name} {len(text.encode("utf-8"))} bytes')
    if BOARD_DATA.parent.exists():
        BOARD_DATA.write_text(board_data(), encoding='utf-8', newline='\n')
        print(f'build: {BOARD_DATA.relative_to(HERE.parents[1])}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
